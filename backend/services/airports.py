"""Airports within reach of one another — the "Nearby" players filter (#3247).

Matching only, never validation: a ``location`` that is not in the dataset is
still valid to store (#2798); it just has no coordinates, so it has no
neighbours. The dataset is ``backend/data/airports.csv`` (OurAirports, public
domain), regenerated by ``backend/scripts/regen_airports.py``.
"""
import csv
from functools import lru_cache
from math import asin, cos, radians, sin, sqrt
from pathlib import Path

# Not a game rule, so not in EraConfig.
NEARBY_RADIUS_MILES = 50
EARTH_RADIUS_MILES = 3958.8
AIRPORTS_PATH = Path(__file__).resolve().parent.parent / "data" / "airports.csv"


@lru_cache(maxsize=1)
def _airports() -> dict[str, tuple[float, float]]:
    with AIRPORTS_PATH.open(encoding="utf-8", newline="") as source:
        rows = csv.DictReader(line for line in source if not line.startswith("#"))
        return {row["code"]: (float(row["lat"]), float(row["lon"])) for row in rows}


def _haversine_miles(first: tuple[float, float], second: tuple[float, float]) -> float:
    lat1, lon1, lat2, lon2 = map(radians, (*first, *second))
    hav = (
        sin((lat2 - lat1) / 2) ** 2
        + cos(lat1) * cos(lat2) * sin((lon2 - lon1) / 2) ** 2
    )
    return 2 * EARTH_RADIUS_MILES * asin(sqrt(hav))


@lru_cache(maxsize=None)
def nearby_airport_codes(code: str) -> frozenset[str] | None:
    """Every code within ``NEARBY_RADIUS_MILES`` of ``code`` (itself included),
    or ``None`` when ``code`` is not in the dataset."""
    airports = _airports()
    origin = airports.get(code)
    if origin is None:
        return None
    return frozenset(
        other
        for other, position in airports.items()
        if _haversine_miles(origin, position) <= NEARBY_RADIUS_MILES
    )
